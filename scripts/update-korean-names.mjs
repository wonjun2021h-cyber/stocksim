// ── 메인 실행 ──────────────────────────────────────────────────────────────────

function main() {
  if (!existsSync(INDEX_PATH)) {
    console.error("❌ index.json 없음:", INDEX_PATH);
    process.exit(1);
  }

  const index = JSON.parse(readFileSync(INDEX_PATH, "utf-8"));
  let updatedCount = 0;
  let skippedCount = 0;
  const unmapped = [];

  for (const entry of index) {
    const korName = KOREAN_NAMES[entry.ticker];
    if (!korName) {
      unmapped.push(entry.ticker);
      skippedCount++;
      continue;
    }
    entry.name = korName;
    updatedCount++;

    // 개별 종목 JSON도 업데이트
    const filePath = join(STOCKS_DIR, `${entry.ticker}.json`);
    if (existsSync(filePath)) {
      try {
        const stock = JSON.parse(readFileSync(filePath, "utf-8"));
        stock.name = korName;
        writeFileSync(filePath, JSON.stringify(stock));
      } catch (e) {
        console.warn(`  ⚠ ${entry.ticker} 파일 업데이트 실패:`, e.message);
      }
    }
  }

  writeFileSync(INDEX_PATH, JSON.stringify(index, null, 2));

  console.log(`\n✅ 완료!`);
  console.log(`   업데이트: ${updatedCount}개`);
  console.log(`   매핑 없음(스킵): ${skippedCount}개`);
  if (unmapped.length > 0) {
    console.log(`\n⚠ 한국어 이름 없는 티커 (티커 그대로 유지):`);
    console.log(`   ${unmapped.join(", ")}`);
  }
}

main();
